import type {
  BudgetItemRecord,
  EventRecord,
  GuestRecord,
  IdeaRecord,
  TimelineItemRecord,
  VendorItemRecord,
} from "@/db/schema";
import type { ReadinessScoreResult } from "./readiness";

export interface EventExportData {
  event: EventRecord;
  readiness?: ReadinessScoreResult;
  budgetItems: BudgetItemRecord[];
  timelineItems: TimelineItemRecord[];
  vendorItems: VendorItemRecord[];
  guests: GuestRecord[];
  ideas: IdeaRecord[];
  exportedAt: string;
}

/**
 * Serializes the full celebration plan into structured JSON.
 */
export function generateEventJson(data: EventExportData): string {
  return JSON.stringify(data, null, 2);
}

/**
 * Compiles a clean, printable Markdown executive brief for clients and vendors.
 */
export function generateEventMarkdown(data: EventExportData): string {
  const { event, readiness, budgetItems, timelineItems, vendorItems, guests, ideas } = data;
  const totalBudget = event.target_budget || 0;
  const totalSpent = budgetItems.reduce((acc, b) => acc + (b.actual_cost || 0), 0);
  const totalEstimated = budgetItems.reduce((acc, b) => acc + (b.estimated_cost || 0), 0);

  let md = `# Celebration Blueprint: ${event.title}\n\n`;
  md += `**Vertical:** ${event.vertical.toUpperCase()} | **Date:** ${event.event_date} | **Location:** ${event.location}\n`;
  md += `**Target Guests:** ${event.guest_count} | **Target Budget:** $${totalBudget.toLocaleString()}\n`;
  md += `**Theme:** ${event.theme}\n\n`;

  if (readiness) {
    md += "## 1. Readiness Assessment\n";
    md += `- **Overall Score:** ${readiness.score}/100 (${readiness.tier})\n`;
    for (const factor of readiness.factors) {
      md += `  - ${factor.name}: ${factor.score}/${factor.maxScore} (${factor.passed ? "PASSED" : "ACTION REQUIRED"})\n`;
    }
    if (readiness.reasons.length > 0) {
      md += "\n**Key Advisories:**\n";
      for (const reason of readiness.reasons) {
        md += `- ${reason}\n`;
      }
    }
    md += "\n---\n\n";
  }

  md += "## 2. Mathematical Budget Allocation\n";
  md += "| Category | Item Name | Estimated | Committed / Actual | Status |\n";
  md += "| :--- | :--- | :--- | :--- | :--- |\n";
  for (const b of budgetItems) {
    md += `| ${b.category} | ${b.name} | $${b.estimated_cost.toLocaleString()} | $${(b.actual_cost || 0).toLocaleString()} | ${b.status} |\n`;
  }
  md += `\n**Total Estimated:** $${totalEstimated.toLocaleString()} | **Committed:** $${totalSpent.toLocaleString()} | **Remaining Buffer:** $${(totalBudget - totalSpent).toLocaleString()}\n\n---\n\n`;

  md += "## 3. Day-of Run-of-Show Timeline\n";
  md += "| Time Window | Phase | Milestone | Responsible Party |\n";
  md += "| :--- | :--- | :--- | :--- |\n";
  const sortedTimeline = [...timelineItems].sort((a, b) => a.order_index - b.order_index);
  for (const t of sortedTimeline) {
    md += `| ${t.time_start} - ${t.time_end} | ${t.phase} | ${t.title} | ${t.responsible_party} |\n`;
  }
  md += "\n---\n\n";

  md += "## 4. Scalable Vendor Procurement\n";
  md += "| Category | Vendor / Service | Target Price | Status | Notes |\n";
  md += "| :--- | :--- | :--- | :--- | :--- |\n";
  for (const v of vendorItems) {
    md += `| ${v.category} | ${v.name} | $${v.price.toLocaleString()} | ${v.status} | ${v.notes || "N/A"} |\n`;
  }
  md += "\n---\n\n";

  md += "## 5. Guest & Hospitality Registry\n";
  const attending = guests.filter((g) => g.rsvp_status === "attending").length;
  const dietaryWarnings = guests.filter(
    (g) =>
      g.dietary_restrictions &&
      g.dietary_restrictions.trim() !== "" &&
      g.dietary_restrictions.toLowerCase() !== "none",
  );
  md += `- **Tracked RSVPs:** ${attending} Confirmed / ${guests.length} Total Registered\n`;
  md += `- **Dietary / Allergen Flags:** ${dietaryWarnings.length} flagged\n`;
  if (dietaryWarnings.length > 0) {
    for (const g of dietaryWarnings) {
      md += `  - ${g.name} (${g.table_number ? `Table ${g.table_number}` : "Unseated"}): ${g.dietary_restrictions}\n`;
    }
  }
  md += "\n---\n\n";

  if (ideas.length > 0) {
    md += "## 6. Curated Creative Concepts & Themes\n";
    for (const idea of ideas) {
      md += `### ${idea.title} (${idea.category})\n`;
      md += `${idea.description}\n`;
      if (idea.ai_rationale) {
        md += `*Design Rationale:* ${idea.ai_rationale}\n`;
      }
      md += "\n";
    }
  }

  md += `\n*Generated by Celebration & Event Planner on ${new Date().toLocaleDateString()}*\n`;
  return md;
}

/**
 * Triggers browser file download for a text payload.
 */
export function downloadFile(filename: string, content: string, mimeType: string): void {
  if (typeof window === "undefined") return;
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
